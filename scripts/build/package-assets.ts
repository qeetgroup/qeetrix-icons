import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { iconMetadata } from "../../config/icon-metadata.js";
import { formatDiagnostics } from "../lib/diagnostics.js";
import { checkGenerationPlan } from "../lib/generated-output.js";
import {
  packageManifestJsonPath,
  packageSvgDirectory,
  planRepositoryGeneration,
} from "../lib/generation-plan.js";
import { maskFreeLogoSvgPath, renderLogoPackageFiles } from "../lib/logo-assets.js";
import { compareLogoOutput } from "../lib/logo-output.js";
import { planLogoGeneration } from "../lib/logo-plan.js";

/**
 * The last step of `bun run build`, after `tsc` has compiled `src/` into `dist/`: writes the
 * package's language-neutral files, for platforms that do not run React.
 *
 * - `dist/svg/<shape>-<variant>/<id>.svg`: every icon drawing, printed from the same generation
 *   plan, and the same element tree, as its committed component;
 * - `dist/manifest.json`: the icon manifest, the same bytes as `icon-manifest.json`;
 * - `dist/svg/logos/<slug>/<variant>.svg`: every logo file as its component embeds it, and
 *   `<variant>.mask-free.svg` beside any drawn with `<mask>`.
 *
 * It refuses to write anything while the committed icon components or logo modules are out of
 * date with their sources, so `dist/` never ships an SVG its component does not draw. It owns
 * `dist/svg/` and `dist/manifest.json` and nothing else.
 */

const repositoryRoot = fileURLToPath(new URL("../../", import.meta.url));
const dist = join(repositoryRoot, "dist");

function fail(message: string): void {
  console.error(message);
  process.exitCode = 1;
}

try {
  const plan = planRepositoryGeneration(repositoryRoot, iconMetadata);
  const iconProblems = checkGenerationPlan(repositoryRoot, plan);
  const logos = planLogoGeneration(repositoryRoot);
  const logoOutput = compareLogoOutput(repositoryRoot, logos.files);
  const logoProblems = [
    ...logos.diagnostics,
    ...logoOutput.stale.map((path) => `${path}: stale; run bun run generate:logos.`),
    ...logoOutput.missing.map((path) => `${path}: missing; run bun run generate:logos.`),
    ...logoOutput.extra.map((path) => `${path}: not generated by generate:logos.`),
  ];
  if (iconProblems.length > 0 || logoProblems.length > 0) {
    if (iconProblems.length > 0) console.error(formatDiagnostics(iconProblems));
    for (const message of logoProblems) console.error(message);
    fail("Packaging aborted: generated output does not match its sources. Nothing was written.");
  } else if (!existsSync(join(dist, "index.js"))) {
    fail("Packaging aborted: dist/ is not built. Run bun run build.");
  } else {
    const logoFiles = await renderLogoPackageFiles(logos);
    rmSync(join(dist, packageSvgDirectory), { recursive: true, force: true });
    rmSync(join(dist, packageManifestJsonPath), { force: true });
    for (const { path, contents } of [...plan.packageFiles, ...logoFiles]) {
      const absolute = join(dist, path);
      mkdirSync(dirname(absolute), { recursive: true });
      writeFileSync(absolute, contents);
    }
    const maskFree = logos.logos.flatMap((logo) =>
      logo.variants
        .map((variant) => maskFreeLogoSvgPath(logo.id, variant.name))
        .filter((path) => logoFiles.some((file) => file.path === path)),
    );
    console.log(
      `Packaged ${plan.packageFiles.length - 1} icon SVG files (${plan.concepts.length} icons), manifest.json, and ${logoFiles.length} logo SVG files (${maskFree.length} mask-free) into dist/.`,
    );
  }
} catch (error) {
  fail(
    `Packaging failed unexpectedly: ${error instanceof Error ? (error.stack ?? error.message) : String(error)}`,
  );
}
