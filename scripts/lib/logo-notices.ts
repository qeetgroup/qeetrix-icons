import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { BrandLicenseClass, BrandLogoData, BrandsData } from "./brands.js";
import { compareText } from "./diagnostics.js";

/** The per-logo license notice, shipped in the package with the other licence texts. */
export const logoNoticesPath = "licenses/third-party-logos.md";
/** Licence texts the notice must reproduce in full. */
export const apacheLicensePath = "licenses/Apache-2.0.txt";

const classLabels: Readonly<Record<BrandLicenseClass, string>> = {
  "public-domain": "Public domain",
  permissive: "Permissive",
  attribution: "Attribution",
  "share-alike": "Share-alike",
  "no-derivatives": "No derivatives",
  "non-commercial": "Non-commercial",
  copyleft: "Copyleft",
  "no-licence": "No licence",
};

const classNotes: Readonly<Record<BrandLicenseClass, string>> = {
  "public-domain": "CC0, Unlicense, or public domain: no conditions.",
  permissive: "MIT, BSD, ISC, or Apache 2.0: keep the notice; Apache 2.0's text is below.",
  attribution: "CC BY: credit the logo (title, source, and license) where you use it.",
  "share-alike": "CC BY-SA: credit it, and share adaptations under the same license.",
  "no-derivatives": "CC BY-ND: credit it, and do not distribute modified versions.",
  "non-commercial": "CC BY-NC: not for commercial use without the owner's permission.",
  copyleft: "GPL, AGPL, LGPL, or MPL: the copyleft terms of the named license apply.",
  "no-licence":
    "No copyright license (brand-use, trademark, fair use, proprietary, or unknown): included on theSVG's nominative fair use basis only; get the owner's permission before relying on it.",
};

/** A Markdown table cell: pipes escaped, line breaks flattened. */
function cell(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

function link(label: string, url: string | null): string {
  return url ? `[${cell(label)}](${url.replace(/\s/g, "%20").replace(/\)/g, "%29")})` : "";
}

function licenseText(logo: BrandLogoData): string {
  if (logo.licenseRaw && logo.licenseRaw !== logo.license) {
    return `${cell(logo.license)}: ${cell(logo.licenseRaw)}`;
  }
  return cell(logo.license);
}

/**
 * `licenses/third-party-logos.md`: where the logos come from, the trademark notice, and every logo with its
 * own license, grouped by licence class, followed by licence texts that must ship in full.
 * Generated from `config/brands.json`, so a re-sync keeps it exact.
 */
export function renderLogoNotices(repositoryRoot: string, data: BrandsData): string {
  const logos = Object.entries(data.logos).sort(([left], [right]) => compareText(left, right));
  const byClass = new Map<BrandLicenseClass, [string, BrandLogoData][]>();
  for (const entry of logos) {
    const group = byClass.get(entry[1].licenseClass) ?? [];
    group.push(entry);
    byClass.set(entry[1].licenseClass, group);
  }
  const order = Object.keys(classLabels) as BrandLicenseClass[];
  const version = data.packageVersion ? `, theSVG ${data.packageVersion}` : "";
  const lines = [
    "# Third-party brand logos",
    "",
    "<!-- Generated by `bun run generate:logos` from config/brands.json. Do not edit by hand. -->",
    "",
    "The brand logos in `@qeetrix/icons` (the SVG files in `icons/brand-icons/` and the logo",
    "components generated from them, in source and in the published build) are taken unmodified",
    `from [theSVG](https://thesvg.org) ([source](${data.source}), commit \`${data.commit}\`${version}).`,
    "theSVG's code and catalogue are licensed under the MIT License; that notice, and those of the",
    "collections theSVG drew from (svgl, lobe-icons, Simple Icons), are reproduced in",
    "[LICENSE](../LICENSE).",
    "",
    "**Each logo keeps its own license**, listed below and recorded in `config/brands.json`, in",
    "`logoManifest` (`@qeetrix/icons/manifest`), and in the header of each generated logo module.",
    "Some licenses restrict use: check a logo's license before you ship it in a product.",
    "",
    "## Trademarks",
    "",
    "Every logo is a trademark of its owner and is provided for identification only. Including it",
    "does not imply endorsement by, affiliation with, or sponsorship by its owner, and grants no",
    "trademark rights. Follow the owner's brand guidelines, linked below where known.",
    "",
    "## Summary",
    "",
    "| License class | Logos | What it means |",
    "|:--|--:|:--|",
    ...order
      .filter((id) => byClass.has(id))
      .map(
        (id) =>
          `| ${classLabels[id]} | ${(byClass.get(id) ?? []).length} | ${cell(classNotes[id])} |`,
      ),
    `| **All** | **${logos.length}** | |`,
    "",
  ];
  for (const id of order) {
    const group = byClass.get(id);
    if (!group) continue;
    lines.push(
      `## ${classLabels[id]} (${group.length})`,
      "",
      cell(classNotes[id]),
      "",
      "| Logo | Id | Collection | License | Source | Guidelines |",
      "|:--|:--|:--|:--|:--|:--|",
      ...group.map(
        ([slug, logo]) =>
          `| ${cell(logo.title)} | \`${slug}\` | ${cell(logo.collection)} | ${licenseText(logo)} | ${link("source", logo.source)} | ${link("guidelines", logo.guidelines)} |`,
      ),
      "",
    );
  }
  const apache = readFileSync(join(repositoryRoot, apacheLicensePath), "utf8").trimEnd();
  lines.push("## Apache License 2.0", "", "```text", apache, "```", "");
  return lines.join("\n");
}
